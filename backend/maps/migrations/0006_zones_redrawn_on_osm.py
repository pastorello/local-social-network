def redraw(apps, schema_editor):
    Zona = apps.get_model('maps', 'Zona')
    for slug, _, geometry in REDRAWN:
        Zona.objects.filter(pk__in=_holding(Zona, slug, SEEDED[slug])).update(geometry=geometry)
    position = max(Zona.objects.values_list('position', flat=True), default=-1)
    for slug, name, geometry in ADDED:
        position += 1
        Zona.objects.get_or_create(slug=slug, defaults={'name': name, 'position': position, 'geometry': geometry})


def undraw(apps, schema_editor):
    Zona = apps.get_model('maps', 'Zona')
    for slug, _, geometry in REDRAWN:
        Zona.objects.filter(pk__in=_holding(Zona, slug, geometry)).update(geometry=SEEDED[slug])
    for slug, _, geometry in ADDED:
        Zona.objects.filter(pk__in=_holding(Zona, slug, geometry)).delete()


def _holding(Zona, slug, geometry):
    # Compared in Python, not in SQL: JSON equality is not portable between
    # SQLite and Postgres, and this is at most eight rows.
    return [zone.pk for zone in Zona.objects.filter(slug=slug) if zone.geometry == geometry]


