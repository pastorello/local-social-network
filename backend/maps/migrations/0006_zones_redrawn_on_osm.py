# The zones redrawn on OpenStreetMap (spec cosa-fare.md Part −1, D2), and two
# added — approved by the author on 2026-10-14.
#
# 0005's six drafts were drawn by hand around five OSM points and ran into the
# sea (17–54% of each). These are cut on the comune's own outline, which in OSM
# follows the coastline, so "inside Gaeta" and "on land" are the same edge;
# each runs about 40 m out to sea so that a pin dropped on the shoreline — a
# beach is all shoreline — is not lost to a zone by its simplification. The
# borders between zones follow what a reader can find on the ground: the
# perimeter of the Parco Urbano Monte Orlando, Porta Carlo III and Porta di
# Terra for the walled town, Via Flacca, Corso Italia and Via Firenze for
# Serapo, and the headlands between beaches along the Flacca. Still
# *indicative* (D2), and simplified to tens of vertices, not the coast to the
# metre; no two zones overlap.
#
# Ariana (with Quaranta Remi) and Arenauta (with San Vito) are zones of their
# own, the author's call: those beaches were in no zone at all.
#
# Derived from OpenStreetMap data, © OpenStreetMap contributors, available
# under the Open Database License 1.0 (https://www.openstreetmap.org/copyright):
# the boundary relation of the Comune di Gaeta (41173), the coastline, the
# beaches and the park, fetched from Overpass on 2026-10-13. [longitude,
# latitude], rings closed, counter-clockwise.
#
# **A zone is redrawn only if it still holds 0005's draft exactly**: one the
# author has corrected in the admin since is left as it is. The same rule runs
# backwards, and an added zone is removed on the way back only if nobody has
# edited it.

